//! Repository file index: respects `.gitignore`/`.ignore`/`.anvilignore`, skips binaries,
//! dependency and build output, and re-parses only files whose size or mtime changed.

use super::symbols::{self, FileSymbols, Symbol};
use globset::{Glob, GlobSet, GlobSetBuilder};
use ignore::WalkBuilder;
use serde::Serialize;
use std::collections::{BTreeMap, HashMap};
