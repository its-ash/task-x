use std::sync::Arc;
use std::time::SystemTime;

pub const MAX_FILE_BYTES: u64 = 1024 * 1024;
pub const MAX_TOTAL_CONTENT_BYTES: u64 = 256 * 1024 * 1024;
pub const MAX_FILES: usize = 200_000;
const BINARY_SNIFF_BYTES: usize = 8 * 1024;
const PROGRESS_EVERY: usize = 250;
/// Bytes sampled to spot minified bundles and files with a generated-code marker.
const GENERATED_SNIFF_BYTES: usize = 16 * 1024;
const GENERATED_MARKERS: &[&str] = &["@generated", "DO NOT EDIT", "Code generated by", "auto-generated", "autogenerated"];

/// True for build output and generated code: a marker in the header, or minified text
/// (very long lines) that no one edits by hand.
pub fn is_generated(text: &str) -> bool {
    let prefix = |s: &str, n: usize| (0..=n.min(s.len())).rev().find(|&i| s.is_char_boundary(i)).unwrap_or(0);
    let sample = &text[..prefix(text, GENERATED_SNIFF_BYTES)];
    let head = &sample[..prefix(sample, 1024)];
    if GENERATED_MARKERS.iter().any(|m| head.contains(m)) {
        return true;
    }
    let lines = sample.lines().count().max(1);
    sample.len() > 2048 && (sample.len() / lines > 300 || sample.lines().any(|l| l.len() > 5000))
}

